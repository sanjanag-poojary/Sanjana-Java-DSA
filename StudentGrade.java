public class StudentGrade {
    public static void main(String[] args) {
        int marks =90;
        if(marks >=85)
        {
            System.out.println("Distinction");
        }
        else if(marks >=60)
        {
            System.out.println("First class");
        }
        else if(marks >=35)
        {
             System.out.println("pass");
        }
        else 
        {
             System.out.println("Fail");
        }

        }
    
}
